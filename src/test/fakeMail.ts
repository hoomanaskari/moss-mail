import { vi } from "vitest";
import type { Account, DraftFile, Person, RecipientPick, SenderRule, Thread } from "../data/types";
import { demoMail, demoStorage, setMail, type MailBackend, type InterruptedSend, type MailEvent, type ScheduleOutcome, type SyncIssue } from "../services/mail";
import type { SavedDraft } from "../state/drafts";
import type { ScheduledEmail } from "../state/scheduled";
import type { SavedSignatures } from "../state/signatures";

/** A live mail backend whose every call is recorded. Installed until the test ends. */
export function fakeMail(overrides: Partial<MailBackend> = {}) {
  const handlers: ((e: MailEvent) => void)[] = [];
  const backend = {
    live: true,
    accounts: vi.fn(async () => []),
    threads: vi.fn(async (): Promise<Thread[]> => []),
    thread: vi.fn(async (): Promise<Thread | undefined> => undefined),
    doneThreads: vi.fn(async (): Promise<Thread[]> => []),
    markDone: vi.fn(async () => {}),
    markNotDone: vi.fn(async () => {}),
    deleteThread: vi.fn(async () => {}),
    restoreThread: vi.fn(async () => {}),
    trashThreads: vi.fn(async (): Promise<Thread[]> => []),
    restoreToInbox: vi.fn(async () => {}),
    markRead: vi.fn(async () => {}),
    blockedThreads: vi.fn(async (): Promise<Thread[]> => []),
    blockSender: vi.fn(async () => {}),
    acceptSender: vi.fn(async () => {}),
    unblockSender: vi.fn(async () => {}),
    senderRules: vi.fn(async (): Promise<SenderRule[]> => []),
    forgetSenderRule: vi.fn(async () => {}),
    snooze: vi.fn(async () => {}),
    moveThread: vi.fn(async () => {}),
    waitForReply: vi.fn(async () => true),
    setSection: vi.fn(async () => {}),
    setSplit: vi.fn(async () => {}),
    clearDeadline: vi.fn(async () => {}),
    remindIfNoReply: vi.fn(async () => true),
    allowImages: vi.fn(async () => {}),
    signatures: vi.fn(async (): Promise<SavedSignatures> => ({ signatures: [], byAccount: {}, byAddress: {}, letMossChoose: true, recent: [] })),
    saveSignature: vi.fn(async () => {}),
    deleteSignature: vi.fn(async () => {}),
    setSignatureChoice: vi.fn(async () => {}),
    setLetMossChoose: vi.fn(async () => {}),
    markSignatureUsed: vi.fn(async () => {}),
    contacts: vi.fn(async (): Promise<Person[]> => []),
    pickRecipient: vi.fn(async () => {}),
    recipientPicks: vi.fn(async (): Promise<RecipientPick[]> => []),
    drafts: vi.fn(async (): Promise<SavedDraft[]> => []),
    saveDraft: vi.fn(async (draft) => draft),
    draftSaveReceipt: vi.fn(async (): Promise<SavedDraft | undefined> => undefined),
    deliveryAttention: vi.fn(demoMail.deliveryAttention),
    deliveryAttentionDraft: vi.fn(demoMail.deliveryAttentionDraft),
    resolveDelivery: vi.fn(demoMail.resolveDelivery),
    localDraftRecoveryIndex: vi.fn(demoMail.localDraftRecoveryIndex),
    localDraftRecovery: vi.fn(demoMail.localDraftRecovery),
    keepLocalDraftRecovery: vi.fn(demoMail.keepLocalDraftRecovery),
    discardLocalDraftRecovery: vi.fn(demoMail.discardLocalDraftRecovery),
    adoptLocalDraftRecovery: vi.fn(demoMail.adoptLocalDraftRecovery),
    deleteDraft: vi.fn(async () => {}),
    discardDraftFile: vi.fn(async () => {}),
    pickFiles: vi.fn(async (): Promise<string[] | File[]> => []),
    attachFiles: vi.fn(async (): Promise<DraftFile[]> => []),
    draftPreview: vi.fn(async (): Promise<string | undefined> => undefined),
    send: vi.fn(async () => {}),
    sendAfter: vi.fn(async () => true),
    cancelSend: vi.fn(async () => ({ cancelled: true, early: true })),
    scheduleSend: vi.fn(async () => ({ status: "scheduled" as const })),
    scheduled: vi.fn(async (): Promise<ScheduledEmail[]> => []),
    rescheduleSend: vi.fn(async (_id: string, _sendAt: number, _operation: string, expectedRevision: number) => ({ status: "rescheduled" as const, revision: expectedRevision + 1 })),
    unscheduleSend: vi.fn(async (): Promise<ScheduleOutcome> => ({ status: "cancelled", early: true })),
    updateAccount: vi.fn(async () => {}),
    addAddress: vi.fn(async (): Promise<Account | undefined> => undefined),
    updateAddress: vi.fn(async (): Promise<Account | undefined> => undefined),
    removeAddress: vi.fn(async (): Promise<Account | undefined> => undefined),
    blockAddress: vi.fn(async (): Promise<Account | undefined> => undefined),
    discoverAddresses: vi.fn(async (): Promise<Account | undefined> => undefined),
    setAddressSignatures: vi.fn(async () => {}),
    reorderAccounts: vi.fn(async () => {}),
    removeAccount: vi.fn(async () => ({ pending: false })),
    credentialCleanupStatus: vi.fn(async () => ({ pending: false })),
    retryCredentialCleanup: vi.fn(async () => ({ pending: false })),
    syncNow: vi.fn(async () => {}),
    syncProgress: vi.fn(async () => undefined),
    syncProblems: vi.fn(async (): Promise<SyncIssue[]> => []),
    serverChangeStatus: vi.fn(async () => null),
    retryServerChange: vi.fn(async () => {}),
    discardServerChange: vi.fn(async () => {}),
    interruptedSends: vi.fn(async (): Promise<InterruptedSend[]> => []),
    dismissInterruptedSends: vi.fn(async () => {}),
    search: vi.fn(async () => []),
    openAttachment: vi.fn(async () => {}),
    attachmentPreview: vi.fn(async (): Promise<string | undefined> => undefined),
    loadMessage: vi.fn(async () => false),
    preload: vi.fn(async () => {}),
    backupStatus: vi.fn(async () => ({ state: "idle" as const })),
    createBackup: vi.fn(async (): Promise<number | null> => null),
    cancelBackup: vi.fn(async () => false),
    storage: vi.fn(async () => demoStorage),
    setOffline: vi.fn(async () => {}),
    setCacheLimit: vi.fn(async () => {}),
    setAttachmentText: vi.fn(async () => {}),
    clearCache: vi.fn(async () => 0),
    rebuildIndex: vi.fn(async () => {}),
    onEvent: vi.fn((handler: (e: MailEvent) => void) => {
      handlers.push(handler);
      return () => handlers.splice(handlers.indexOf(handler), 1);
    }),
    ...overrides,
  } satisfies MailBackend;
  setMail(backend);
  /** Sends an engine event to everyone listening. */
  const emit = (e: MailEvent) => handlers.forEach((h) => h(e));
  return { backend, emit, listening: () => handlers.length };
}
